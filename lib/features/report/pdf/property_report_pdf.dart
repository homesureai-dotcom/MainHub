import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../models/report_export_model.dart';

class PropertyReportPdf {
  const PropertyReportPdf._();

  static Future<Uint8List> build(
    ReportExportModel report,
  ) async {
    final pdf = pw.Document(
      title: 'Property Intelligence Report',
      author: 'HomeSure AI',
    );

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _cover(report),
        ],
      ),
    );

    return pdf.save();
  }

  static pw.Widget _cover(ReportExportModel report) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Text(
          "HomeSure AI",
          style: pw.TextStyle(
            fontSize: 30,
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.blue800,
          ),
        ),

        pw.SizedBox(height: 6),

        pw.Text(
          "Residential Property Intelligence Platform",
          style: const pw.TextStyle(
            fontSize: 14,
            color: PdfColors.grey700,
          ),
        ),

        pw.SizedBox(height: 30),

        pw.Divider(),

        pw.SizedBox(height: 20),

        pw.Text(
          "PROPERTY INTELLIGENCE REPORT",
          style: pw.TextStyle(
            fontSize: 22,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 40),

        pw.Text(
          report.propertyName,
          style: pw.TextStyle(
            fontSize: 24,
            fontWeight: pw.FontWeight.bold,
          ),
          textAlign: pw.TextAlign.center,
        ),

        pw.SizedBox(height: 12),

        pw.Text(
          "${report.city}, ${report.state}",
          style: const pw.TextStyle(fontSize: 16),
        ),

        pw.SizedBox(height: 40),

        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(24),
          decoration: pw.BoxDecoration(
            border: pw.Border.all(
              color: PdfColors.blue400,
            ),
            borderRadius: pw.BorderRadius.circular(10),
            color: PdfColors.blue50,
          ),
          child: pw.Column(
            children: [
              pw.Text(
                "PROPERTY HEALTH SCORE",
                style: pw.TextStyle(
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 16,
                ),
              ),

              pw.SizedBox(height: 20),

              pw.Text(
                report.overallScore.toString(),
                style: pw.TextStyle(
                  fontSize: 60,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blue800,
                ),
              ),

              pw.SizedBox(height: 10),

              pw.Text(
                report.grade.toUpperCase(),
                style: pw.TextStyle(
                  fontSize: 20,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ],
          ),
        ),

        pw.SizedBox(height: 40),

        _info("Owner", report.ownerName),
        _info("Builder", report.builderName),
        _info("Assessment Date", report.assessmentDate),
        _info("Report ID", report.reportId),

        pw.SizedBox(height: 40),

        pw.Divider(),

        pw.Text(
          "Generated by SureBot AI",
          style: const pw.TextStyle(
            color: PdfColors.grey700,
          ),
        ),

        pw.SizedBox(height: 8),

        pw.Text(
          "© HomeSure AI",
          style: const pw.TextStyle(
            color: PdfColors.grey700,
          ),
        ),
      ],
    );
  }

  static pw.Widget _info(
    String title,
    String value,
  ) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 12),
      child: pw.Row(
        children: [
          pw.SizedBox(
            width: 130,
            child: pw.Text(
              title,
              style: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(value),
          ),
        ],
      ),
    );
  }
}