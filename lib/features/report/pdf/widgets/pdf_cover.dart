import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../models/report_export_model.dart';
import '../report_theme.dart';

class PdfCover {
  PdfCover._();

  static pw.Widget build(
    ReportExportModel report,
  ) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(32),
      decoration: pw.BoxDecoration(
        color: ReportTheme.background,
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.center,
        children: [
          pw.Text(
            "HomeSure AI",
            style: ReportTheme.title(),
          ),

          pw.SizedBox(height: ReportTheme.sm),

          pw.Text(
            "Residential Property Intelligence Platform",
            style: ReportTheme.body(),
          ),

          pw.SizedBox(height: ReportTheme.xl),

          pw.Divider(
            color: ReportTheme.divider,
          ),

          pw.SizedBox(height: ReportTheme.lg),

          pw.Text(
            "PROPERTY HEALTH CERTIFICATE",
            style: ReportTheme.reportTitle(),
            textAlign: pw.TextAlign.center,
          ),

          pw.SizedBox(height: ReportTheme.xxl),

          pw.Text(
            report.propertyName,
            style: ReportTheme.sectionTitle(),
            textAlign: pw.TextAlign.center,
          ),

          pw.SizedBox(height: ReportTheme.sm),

          pw.Text(
            "${report.city}, ${report.state}",
            style: ReportTheme.body(),
          ),

          pw.SizedBox(height: ReportTheme.xxl),

          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(24),
            decoration: pw.BoxDecoration(
              color: PdfColors.white,
              border: pw.Border.all(
                color: ReportTheme.primaryBlue,
              ),
              borderRadius: pw.BorderRadius.circular(12),
            ),
            child: pw.Column(
              children: [
                pw.Text(
                  "HomeSure Property Health Score™",
                  style: ReportTheme.label(),
                ),

                pw.SizedBox(height: ReportTheme.md),

                pw.Text(
                  report.overallScore.toString(),
                  style: ReportTheme.score(),
                ),

                pw.SizedBox(height: ReportTheme.sm),

                pw.Text(
                  report.grade.toUpperCase(),
                  style: ReportTheme.grade(),
                ),
              ],
            ),
          ),

          pw.SizedBox(height: ReportTheme.xl),

          _info("Prepared For", report.ownerName),

          _info("Builder", report.builderName),

          _info("Assessment Date", report.assessmentDate),

          _info("Report ID", report.reportId),

          pw.SizedBox(height: ReportTheme.xxl),

          pw.Divider(),

          pw.SizedBox(height: ReportTheme.md),

          pw.Text(
            "Generated by SureBot AI™",
            style: ReportTheme.sectionTitle(),
          ),

          pw.SizedBox(height: ReportTheme.sm),

          pw.Text(
            "Your property has been digitally assessed using the HomeSure AI Property Intelligence Framework.",
            textAlign: pw.TextAlign.center,
            style: ReportTheme.body(),
          ),
        ],
      ),
    );
  }

  static pw.Widget _info(
    String title,
    String value,
  ) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 14),
      child: pw.Row(
        children: [
          pw.SizedBox(
            width: 140,
            child: pw.Text(
              title,
              style: ReportTheme.label(),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: ReportTheme.value(),
            ),
          ),
        ],
      ),
    );
  }
}