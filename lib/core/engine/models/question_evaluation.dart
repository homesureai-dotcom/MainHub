import '../../../core/phs/phs_categories.dart';
import '../../../models/property_health/property_risk.dart';
import '../../../models/property_health/recommendation.dart';

/// Result produced after evaluating a single assessment question.
///
/// This is the intermediate result used by the Property Intelligence
/// Engine before the individual question results are aggregated into
/// a complete PropertyHealthResult.
class QuestionEvaluation {
  /// PHS category associated with the question.
  final PHSCategory category;

  /// Score earned for this question.
  final double score;

  /// Maximum possible score for this question.
  final double maxScore;

  /// Risk generated by the answer, if any.
  final PropertyRisk? risk;

  /// Recommendation generated by the answer, if any.
  final Recommendation? recommendation;

  const QuestionEvaluation({
    required this.category,
    required this.score,
    required this.maxScore,
    this.risk,
    this.recommendation,
  });

  /// Percentage score for this individual question.
  double get percentage {
    if (maxScore == 0.0) {
      return 0.0;
    }

    return (score / maxScore) * 100.0;
  }

  /// Whether this evaluation generated a risk.
  bool get hasRisk => risk != null;

  /// Whether this evaluation generated a recommendation.
  bool get hasRecommendation => recommendation != null;
}